// Builds M3-COVERAGE.md from its feature rows and coverage/m3-status.txt.
// Fails if the two ID sets differ. Usage: node scripts/gen-coverage-m3.mjs
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const web = join(here, "..");
const existing = readFileSync(join(web, "M3-COVERAGE.md"), "utf8");
const featureRows = existing
  .split("\n")
  .map((l) => /^\|\s*([A-Z]+-\d+)\s*\|\s*([^|]+?)\s*\|\s*(done|partial|not done|server only)\s*\|/.exec(l))
  .filter(Boolean)
  .map((m) => ({ id: m[1], feature: m[2] }));
const status = new Map();
for (const line of readFileSync(join(web, "coverage/m3-status.txt"), "utf8").split("\n")) {
  if (!line.trim() || line.startsWith("#")) continue;
  const [id, st, ...rest] = line.split("|");
  if (!["done", "partial", "not"].includes(st)) throw new Error(`bad status for ${id}: ${st}`);
  if (status.has(id)) throw new Error(`duplicate ${id}`);
  status.set(id, { st, proof: rest.join("|").trim() });
}
const featureIds = new Set(featureRows.map((r) => r.id));
const missing = [...featureIds].filter((id) => !status.has(id));
const extra = [...status.keys()].filter((id) => !featureIds.has(id));
if (missing.length || extra.length) throw new Error(`ID mismatch. missing: ${missing.join(", ")} extra: ${extra.join(", ")}`);
const KEYS = new Set(["E:zm4/KANB", "E:zm4/CNT", "U:sync", "U:limits", "U:views", "U:m3", "U:m3sync", "U:core", ...["KANB", "TIME", "CALW", "MTRX", "VMODE"].map((k) => `E:views/${k}`), ...["CALV", "CALW", "FEAT", "KANB", "TIME", "MTRX"].map((k) => `E:ui/${k}`), ...["QA", "HL", "DET", "REP", "DRAG", "OFF", "CONV"].map((k) => `E:core/${k}`), ...["MENU", "LIFE", "DP", "DUR", "LH", "LIST", "TAG", "COMP", "SRCH", "KEYS", "QAM", "SET", "STRUCT", "ATT"].map((k) => `E:ui/${k}`)]);
const bad = [];
for (const [id, s] of status) {
  const refs = s.proof.match(/\b[UES]:[A-Za-z0-9/_-]+/g) ?? [];
  for (const r of refs) {
    if (r.startsWith("S:")) {
      if (!existsSync(join(web, "screens", `${r.slice(2)}.png`))) bad.push(`${id}: ${r} (no screenshot)`);
    } else if (!KEYS.has(r)) bad.push(`${id}: ${r} (unknown key)`);
  }
  if (s.st === "done" && refs.length === 0) bad.push(`${id}: done without a proof reference`);
}
if (bad.length) throw new Error(`proof problems:\n${bad.join("\n")}`);

const count = (st) => [...status.values()].filter((s) => s.st === st).length;
const label = { done: "done", partial: "partial", not: "not done" };
const out = [
  "# M3 coverage (web client)",
  "",
  "Generated by `node scripts/gen-coverage-m3.mjs` from `coverage/m3-status.txt` and the M3 feature list below. The script fails when the ID sets differ or when a done row has no test or screenshot reference.",
  "",
  `Rows: ${featureRows.length}. Done ${count("done")}, partial ${count("partial")}, not done ${count("not")}.`,
  "",
  "Done means a test or a screenshot proves the behaviour. Partial means built but unproven, or built with a stated gap. Not done means not built.",
  "",
  "## Proof keys",
  "",
  "- `U:m3`: `test/m3.test.ts` (kanban lanes and order, timeline DST math, calendar overlap and span layout, item kinds, routes). `U:m3sync`: `test/m3sync.test.ts` (columns, ext sections, calendar settings, matrix order against the real server in-process). `U:core`: `packages/core/test/filterRule.test.ts` (filter rules, date tokens, matrix presets, drag patches).",
  "- `E:views/KANB|TIME|CALW|MTRX|VMODE`: `e2e/views.spec.ts` (card between columns + reload; timeline bar drag and resize; week block drag and resize; matrix quadrant drag changes priority; view mode persists after reload and in a second context).",
  "- `E:ui/CALV|CALW|FEAT|KANB|TIME|MTRX`: `e2e/views-ui.spec.ts` (calendar views/options/shortcuts; calendar writes; feature switches and mini calendar; kanban sections and Today board; timeline zoom/group/add; matrix rules and views).",
  "- Calendar library: none. The grids are custom (CalGrid.tsx, Calendar.tsx) so they use the design tokens and the sync data model directly.",
  "- Server changes wanted (not made here): `GET/POST /api/v2/matrixProfiles(/batch)` (profiles live in ext.matrixProfiles meanwhile); column deletes are not reported by `column?from=` (client pulls from=0).",
  "- `S:<name>`: `screens/<name>.png` (synthetic data, desktop 1440x900, phone 390x844). The generator checks each file exists.",
  "",
  "| ID | Feature | Status | Proof / note |",
  "|---|---|---|---|",
  ...featureRows.map((r) => {
    const s = status.get(r.id);
    return `| ${r.id} | ${r.feature.replace(/\|/g, "/")} | ${label[s.st]} | ${s.proof.replace(/\|/g, "/")} |`;
  }),
  "",
];
writeFileSync(join(web, "M3-COVERAGE.md"), out.join("\n"));
console.log(`M3 rows ${featureRows.length}: done ${count("done")}, partial ${count("partial")}, not done ${count("not")}`);
