// Builds M5-COVERAGE.md from its feature rows and coverage/m5-status.txt.
// Fails if the two ID sets differ, if a done row has no proof reference, or if a reference is unknown.
// Usage: node scripts/gen-coverage-m5.mjs
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const web = join(here, "..");
const existing = readFileSync(join(web, "M5-COVERAGE.md"), "utf8");
const featureRows = existing
  .split("\n")
  .map((l) => /^\|\s*([A-Z]+-\d+)\s*\|\s*([^|]+?)\s*\|\s*(done|partial|not done|server only)\s*\|/.exec(l))
  .filter(Boolean)
  .map((m) => ({ id: m[1], feature: m[2] }));
const STATES = ["done", "partial", "not", "server"];
const status = new Map();
for (const line of readFileSync(join(web, "coverage/m5-status.txt"), "utf8").split("\n")) {
  if (!line.trim() || line.startsWith("#")) continue;
  const [id, st, ...rest] = line.split("|");
  if (!STATES.includes(st)) throw new Error(`bad status for ${id}: ${st}`);
  if (status.has(id)) throw new Error(`duplicate ${id}`);
  status.set(id, { st, proof: rest.join("|").trim() });
}
const featureIds = new Set(featureRows.map((r) => r.id));
const missing = [...featureIds].filter((id) => !status.has(id));
const extra = [...status.keys()].filter((id) => !featureIds.has(id));
if (missing.length || extra.length) throw new Error(`ID mismatch. missing: ${missing.join(", ")} extra: ${extra.join(", ")}`);
const E = ["RMD1", "RMD2", "NTF", "PUSH", "CMT", "ATT", "TPL", "GAL", "FILT", "SRCH", "ACT", "BAK", "INTG", "SETX", "REST"];
const KEYS = new Set(["U:m5filters", "U:m5csv", "U:m5notify", "U:m5sync", "E:ui", ...E.map((k) => `E:zm5/${k}`)]);
const bad = [];
for (const [id, s] of status) {
  const refs = s.proof.match(/\b[UES]:[A-Za-z0-9/_-]+/g) ?? [];
  for (const r of refs) {
    if (r.startsWith("S:")) {
      if (!existsSync(join(web, "screens", `${r.slice(2)}.png`))) bad.push(`${id}: ${r} (no screenshot)`);
    } else if (!KEYS.has(r)) bad.push(`${id}: ${r} (unknown key)`);
  }
  if (s.st === "done" && refs.length === 0) bad.push(`${id}: done without a proof reference`);
}
if (bad.length) throw new Error(`proof problems:\n${bad.join("\n")}`);

const count = (st) => [...status.values()].filter((s) => s.st === st).length;
const label = { done: "done", partial: "partial", not: "not done", server: "server only" };
const out = [
  "# M5 coverage (web client)",
  "",
  "Generated by `node scripts/gen-coverage-m5.mjs` from `coverage/m5-status.txt` and the M5 feature list below. The script fails when the ID sets differ, when a done row has no test or screenshot reference, or when a reference is unknown.",
  "",
  `Rows: ${featureRows.length}. Done ${count("done")}, partial ${count("partial")}, not done ${count("not")}, server only ${count("server")}.`,
  "",
  "Done means a web test or a screenshot proves the behaviour in the client. Partial means built but unproven, or built with a stated gap. Not done means not built (or blocked on a server part that is not built). Server only means the row has no web part (limits, quotas, server math) and is proven in `apps/server/M5-COVERAGE.md`; those rows are not counted as web done.",
  "",
  "## How reminders reach the screen",
  "",
  "The server computes reminder instances (`GET /api/v2/reminder/instances`). While the app is open it polls the next six hours (on start, every minute and after each sync that changed a task with reminders) and fires each instance on time: an in-app card with Snooze (`/reminder/delay`), Complete and Got it (`/task/closeRemind`), plus a notification-centre row with the same id the server uses. With the app closed, Web Push delivers: Settings > Notifications > Web Reminder registers the subscription (`/push/register`, VAPID key from `/push/vapidPublicKey`), the service worker (`public/sw.js` with `public/sw-notify.js`) shows the notification and a click focuses or opens the task. The server writes a centre row only after a push is delivered, so rows fired in the app are kept on this device and merged with the server list.",
  "",
  "## Proof keys",
  "",
  "- `U:m5filters`: `test/m5filters.test.ts` (rule builder serialisation round trip for normal and nested AND/OR/NOT trees, legacy text, meaning checked against the shared evaluator, open-only matching, preview order, defaults for a new task in a filter view).",
  "- `U:m5csv`: `test/m5csv.test.ts` (CSV import preview parsing: RFC 4180 cells, UTF-8 BOM, preamble and status legend, refusal without a header, and the preview of the server's own export with equal counts).",
  "- `U:m5notify`: `test/m5notify.test.ts` (notification click routing: `sw-notify.js` and the app route every payload kind the same way; `sw.js` run in a sandbox focuses an open window and routes it, opens a window when none is open, shows a push with its payload; centre row ids match the server's formula and merge without duplicates; the voice memo recorder stops at 30 minutes).",
  "- `U:m5sync`: `test/m5sync.test.ts` (custom filters sync between two clients through `batch/filter` and `deletedFilters`; a filter deleted before its push never reaches the server).",
  "- `E:zm5/RMD1|RMD2|NTF|PUSH|CMT|ATT|TPL|GAL|FILT|SRCH|ACT|BAK|INTG|SETX|REST`: `e2e/zm5.spec.ts` against the real server on synthetic data (reminder picker presets, custom and constant; a reminder firing on time with snooze, centre row and close; deep link and notification settings; push registration; comments with an image; paste, drop, upload, preview and download of attachments; save and use templates and the manager; the list template gallery; the advanced filter builder with live preview and the saved filter view; search to filter; task and list activity; Generate Backup then Import Backups into a fresh account on a second server with equal counts; the Integrations tab with habit and focus export; holidays, habit constant reminder and per-filter sort; print paths, default reminders, note template, comment edit and delete, attachment remove, email address).",
  "- `E:ui`: `e2e/ui.spec.ts` (M2 tests that cover M5 rows: task menu order, add bar menu order, upload probe).",
  "- `S:<name>`: `screens/<name>.png` (synthetic data, desktop 1440x900 and phone 390x844, from `e2e/zm5-screens.spec.ts`, run with `SCREENS=1`). The generator checks each file exists.",
  "- Test stand-ins: headless Chromium has no push service and reports the notification permission as denied, so the push test replaces only `PushManager.prototype.subscribe` and the permission getter; the app code and the server registration run as is. A real delivery through a push service is not tested.",
  "",
  "## Server changes wanted (not made here)",
  "",
  "- Notification centre rows only appear after a push is delivered (`dispatchDue`). Writing the row when a reminder falls due (with or without a subscription) would let every device show it; meanwhile the web app keeps rows it fired itself.",
  "- No test hook to fire reminders at a chosen time (the clock is only injectable in-process), so the e2e uses real time a few seconds ahead.",
  "- `POST /api/v2/push/stats/arrive` needs the CSRF header, which a service worker cannot read from the cookie; RMD-033 telemetry is skipped.",
  "- No route to save a list as a list template (TPL-022 says NoorTasks adds no entry, so none was built); third-party importers (IMP-026..032) and outbound email (NTF-014) are server not done.",
  "- `M5-ASSUMPTIONS.md` names the third seeded list template \"Bug Triage\"; the server seeds \"Reading List\".",
  "",
  "| ID | Feature | Status | Proof / note |",
  "|---|---|---|---|",
  ...featureRows.map((r) => {
    const s = status.get(r.id);
    return `| ${r.id} | ${r.feature.replace(/\|/g, "/")} | ${label[s.st]} | ${s.proof.replace(/\|/g, "/")} |`;
  }),
  "",
];
writeFileSync(join(web, "M5-COVERAGE.md"), out.join("\n"));
console.log(`M5 rows ${featureRows.length}: done ${count("done")}, partial ${count("partial")}, not done ${count("not")}, server only ${count("server")}`);
