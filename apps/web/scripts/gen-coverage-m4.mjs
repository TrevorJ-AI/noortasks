// Builds M4-COVERAGE.md from its feature rows and coverage/m4-status.txt.
// Fails if the two ID sets differ. Usage: node scripts/gen-coverage-m4.mjs
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const web = join(here, "..");
const existing = readFileSync(join(web, "M4-COVERAGE.md"), "utf8");
const featureRows = existing
  .split("\n")
  .map((l) => /^\|\s*([A-Z]+-\d+)\s*\|\s*([^|]+?)\s*\|\s*(done|partial|not done|server only)\s*\|/.exec(l))
  .filter(Boolean)
  .map((m) => ({ id: m[1], feature: m[2] }));
const status = new Map();
for (const line of readFileSync(join(web, "coverage/m4-status.txt"), "utf8").split("\n")) {
  if (!line.trim() || line.startsWith("#")) continue;
  const [id, st, ...rest] = line.split("|");
  if (!["done", "partial", "not"].includes(st)) throw new Error(`bad status for ${id}: ${st}`);
  if (status.has(id)) throw new Error(`duplicate ${id}`);
  status.set(id, { st, proof: rest.join("|").trim() });
}
const featureIds = new Set(featureRows.map((r) => r.id));
const missing = [...featureIds].filter((id) => !status.has(id));
const extra = [...status.keys()].filter((id) => !featureIds.has(id));
if (missing.length || extra.length) throw new Error(`ID mismatch. missing: ${missing.join(", ")} extra: ${extra.join(", ")}`);
const KEYS = new Set(["U:m4timer", "U:m4habits", "U:m4sync", "U:stats", "U:countdown", "U:summary", ...["FEAT", "HAB1", "HAB2", "HAB3", "POMO", "REC", "SYNC", "KANB", "CNT", "STAT", "SUM"].map((k) => `E:zm4/${k}`)]);
const bad = [];
for (const [id, s] of status) {
  const refs = s.proof.match(/\b[UES]:[A-Za-z0-9/_-]+/g) ?? [];
  for (const r of refs) {
    if (r.startsWith("S:")) {
      if (!existsSync(join(web, "screens", `${r.slice(2)}.png`))) bad.push(`${id}: ${r} (no screenshot)`);
    } else if (!KEYS.has(r)) bad.push(`${id}: ${r} (unknown key)`);
  }
  if (s.st === "done" && refs.length === 0) bad.push(`${id}: done without a proof reference`);
}
if (bad.length) throw new Error(`proof problems:\n${bad.join("\n")}`);

const count = (st) => [...status.values()].filter((s) => s.st === st).length;
const label = { done: "done", partial: "partial", not: "not done" };
const out = [
  "# M4 coverage (web client)",
  "",
  "Generated by `node scripts/gen-coverage-m4.mjs` from `coverage/m4-status.txt` and the M4 feature list below. The script fails when the ID sets differ or when a done row has no test or screenshot reference.",
  "",
  `Rows: ${featureRows.length}. Done ${count("done")}, partial ${count("partial")}, not done ${count("not")}.`,
  "",
  "Done means a test or a screenshot proves the behaviour. Partial means built but unproven, or built with a stated gap. Not done means not built. Habit, focus and countdown screen layouts follow our design choices noted in docs.",
  "",
  "## Proof keys",
  "",
  "- `U:m4timer`: `test/m4timer.test.ts` (timer state machine: countdown and count-up, pause and resume fragments, late wake-up ends on schedule, break lengths and long-break interval, auto mode, records, cross-device follow and takeover). `U:m4habits`: `test/m4habits.test.ts` (habit rules, defaults, streak and monthly-rate display math, day states, weekly review, sorting).",
  "- `U:m4sync`: `test/m4sync.test.ts` (against the real server in-process: habits, check-ins incl. two devices on one day, logs, skip, archive, delete, limits; focus records by delta and tombstone, Delete All, timers; preferences; countdown pin slot and 400 countdowns; live focus ops between two clients; localStorage timer state).",
  "- `U:stats`, `U:countdown`, `U:summary`: `test/stats.test.ts`, `test/countdown.test.ts`, `test/summary.test.ts` (statistics aggregation and badge math, countdown day math and repeats, summary filters, grouping, sorting and Markdown).",
  "- `E:zm4/FEAT|HAB1|HAB2|HAB3|POMO|REC|SYNC|KANB|CNT|STAT|SUM`: `e2e/zm4.spec.ts` (feature switches and settings tabs; habit create and check-in and Today; past check-in edit, skip, streak badge; amount goal, log popup, card layout, sections, archive, delete; a Pomodoro linked to a task run to its end with Playwright's clock, record and statistics; manual records, stopwatch, replace prompt; a timer started in one browser context shown in another; kanban Progress offer; countdown add and calendar overlays; statistics overlay; summary).",
  "- Server changes wanted (not made here): a countdown image upload route (`POST /api/v1/attachment/upload/countdown`, ATT-902); `GET /api/v2/data/export/habits` and `/data/export/pomodoro` (IMP-022, IMP-023; the client exports CSV meanwhile); a way to write a task's estimate (`focusSummaries[].estimatedPomo/estimatedDuration` are server owned and the client strips them, FOC-017); `v3/user/ranking` returns 0 where ACC-019 says a fixed 0.99.",
  "- `S:<name>`: `screens/<name>.png` (synthetic data, desktop 1440x900, phone 390x844, from `e2e/zm4-screens.spec.ts`). The generator checks each file exists.",
  "",
  "| ID | Feature | Status | Proof / note |",
  "|---|---|---|---|",
  ...featureRows.map((r) => {
    const s = status.get(r.id);
    return `| ${r.id} | ${r.feature.replace(/\|/g, "/")} | ${label[s.st]} | ${s.proof.replace(/\|/g, "/")} |`;
  }),
  "",
];
writeFileSync(join(web, "M4-COVERAGE.md"), out.join("\n"));
console.log(`M4 rows ${featureRows.length}: done ${count("done")}, partial ${count("partial")}, not done ${count("not")}`);
