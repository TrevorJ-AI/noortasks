// Builds M2-COVERAGE.md from its feature rows and coverage/m2-status.txt.
// Fails if the two ID sets differ. Usage: node scripts/gen-coverage.mjs
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const web = join(here, "..");
const existing = readFileSync(join(web, "M2-COVERAGE.md"), "utf8");
const featureRows = existing
  .split("\n")
  .map((l) => /^\|\s*([A-Z]+-\d+)\s*\|\s*([^|]+?)\s*\|\s*(done|partial|not done|server only)\s*\|/.exec(l))
  .filter(Boolean)
  .map((m) => ({ id: m[1], feature: m[2] }));
const status = new Map();
for (const line of readFileSync(join(web, "coverage/m2-status.txt"), "utf8").split("\n")) {
  if (!line.trim() || line.startsWith("#")) continue;
  const [id, st, ...rest] = line.split("|");
  if (!["done", "partial", "not"].includes(st)) throw new Error(`bad status for ${id}: ${st}`);
  if (status.has(id)) throw new Error(`duplicate ${id}`);
  status.set(id, { st, proof: rest.join("|").trim() });
}
const featureIds = new Set(featureRows.map((r) => r.id));
const missing = [...featureIds].filter((id) => !status.has(id));
const extra = [...status.keys()].filter((id) => !featureIds.has(id));
if (missing.length || extra.length) throw new Error(`ID mismatch. missing: ${missing.join(", ")} extra: ${extra.join(", ")}`);
const KEYS = new Set(["U:sync", "U:limits", "U:views", ...["QA", "HL", "DET", "REP", "DRAG", "OFF", "CONV"].map((k) => `E:core/${k}`), ...["MENU", "LIFE", "DP", "DUR", "LH", "LIST", "TAG", "COMP", "SRCH", "KEYS", "QAM", "SET", "STRUCT", "ATT"].map((k) => `E:ui/${k}`)]);
const bad = [];
for (const [id, s] of status) {
  const refs = s.proof.match(/\b[UES]:[A-Za-z0-9/_-]+/g) ?? [];
  for (const r of refs) {
    if (r.startsWith("S:")) {
      if (!existsSync(join(web, "screens", `${r.slice(2)}.png`))) bad.push(`${id}: ${r} (no screenshot)`);
    } else if (!KEYS.has(r)) bad.push(`${id}: ${r} (unknown key)`);
  }
  if (s.st === "done" && refs.length === 0) bad.push(`${id}: done without a proof reference`);
}
if (bad.length) throw new Error(`proof problems:\n${bad.join("\n")}`);

const count = (st) => [...status.values()].filter((s) => s.st === st).length;
const label = { done: "done", partial: "partial", not: "not done" };
const out = [
  "# M2 coverage (web client)",
  "",
  "Generated by `node scripts/gen-coverage.mjs` from `coverage/m2-status.txt` and the M2 feature list below. The script fails when the ID sets differ or when a done row has no test or screenshot reference.",
  "",
  `Rows: ${featureRows.length}. Done ${count("done")}, partial ${count("partial")}, not done ${count("not")}.`,
  "",
  "Done means a test or a screenshot proves the behaviour. Partial means built but unproven, or built with a stated gap. Not done means not built.",
  "",
  "## Proof keys",
  "",
  "- `U:sync`, `U:limits`: `test/sync.test.ts` (sync engine against the real server in-process; the limits block). `U:views`: `test/views.test.ts`.",
  "- `E:core/QA` quick add with date, tag and priority; `E:core/HL` click a highlight to cancel it; `E:core/DET` detail edit persists; `E:core/REP` repeating task rolls over; `E:core/DRAG` drag reorder survives reload; `E:core/OFF` offline edit syncs; `E:core/CONV` two contexts converge. File: `e2e/core.spec.ts`.",
  "- `E:ui/MENU` more menu, priority menu, list picker; `E:ui/LIFE` pin, won't do, duplicate, convert to note, delete with undo, trash restore; `E:ui/DP` date picker presets, custom repeat, reminders, clear; `E:ui/DUR` duration tab; `E:ui/LH` list header menus; `E:ui/LIST` add list dialog, list menu, rename, delete; `E:ui/TAG` tags; `E:ui/COMP` completed screen; `E:ui/SRCH` search and command menu; `E:ui/KEYS` keyboard; `E:ui/QAM` quick-add menu, batch paste, list marker; `E:ui/SET` settings; `E:ui/STRUCT` subtasks, checklist, slash menu, multi-select, drag onto a list; `E:ui/ATT` attachment upload. File: `e2e/ui.spec.ts`.",
  "- `S:<name>`: `screens/<name>.png` (synthetic data, desktop 1440x900, phone 390x844). The generator checks each file exists.",
  "",
  "| ID | Feature | Status | Proof / note |",
  "|---|---|---|---|",
  ...featureRows.map((r) => {
    const s = status.get(r.id);
    return `| ${r.id} | ${r.feature.replace(/\|/g, "/")} | ${label[s.st]} | ${s.proof.replace(/\|/g, "/")} |`;
  }),
  "",
];
writeFileSync(join(web, "M2-COVERAGE.md"), out.join("\n"));
console.log(`M2 rows ${featureRows.length}: done ${count("done")}, partial ${count("partial")}, not done ${count("not")}`);
