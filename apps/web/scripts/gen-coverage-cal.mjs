// Builds CAL-COVERAGE.md from its feature rows and coverage/cal-status.txt.
// In scope: the CAL- rows about subscriptions, accounts, feeds and showing external events (listed below).
// Fails if a scoped ID is missing from the table or the status file, if a done row has no proof, or a proof key is unknown.
// Usage: node scripts/gen-coverage-cal.mjs
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const web = join(here, "..");
const SCOPE = ["CAL-028", "CAL-050", ...Array.from({ length: 21 }, (_, i) => `CAL-0${61 + i}`), "CAL-087", "CAL-901", "CAL-902"];
const existing = readFileSync(join(web, "CAL-COVERAGE.md"), "utf8");
const featureRows = new Map();
for (const l of existing.split("\n")) {
  const m = /^\|\s*([A-Z]+-\d+)\s*\|\s*([^|]+?)\s*\|\s*(done|partial|not done|server only)\s*\|/.exec(l);
  if (m) featureRows.set(m[1], m[2]);
}
const STATES = ["done", "partial", "not", "server"];
const status = new Map();
for (const line of readFileSync(join(web, "coverage/cal-status.txt"), "utf8").split("\n")) {
  if (!line.trim() || line.startsWith("#")) continue;
  const [id, st, ...rest] = line.split("|");
  if (!STATES.includes(st)) throw new Error(`bad status for ${id}: ${st}`);
  if (status.has(id)) throw new Error(`duplicate ${id}`);
  status.set(id, { st, proof: rest.join("|").trim() });
}
const notInTable = SCOPE.filter((id) => !featureRows.has(id));
const missing = SCOPE.filter((id) => !status.has(id));
const extra = [...status.keys()].filter((id) => !SCOPE.includes(id));
if (notInTable.length || missing.length || extra.length) throw new Error(`ID mismatch. not in table: ${notInTable} missing: ${missing} extra: ${extra}`);
const E = ["CAT", "OAUTH", "DAV", "HOL", "SUB", "VIEWS", "HIDE", "COLOR", "SIDE", "FEED", "DISP", "DEL", "ACCT"];
const KEYS = new Set(["U:calext", ...E.map((k) => `E:zm7cal/${k}`)]);
const bad = [];
for (const [id, s] of status) {
  const refs = s.proof.match(/\b[UES]:[A-Za-z0-9/_-]+/g) ?? [];
  for (const r of refs) {
    if (r.startsWith("S:")) {
      if (!existsSync(join(web, "screens", `${r.slice(2)}.png`))) bad.push(`${id}: ${r} (no screenshot)`);
    } else if (!KEYS.has(r)) bad.push(`${id}: ${r} (unknown key)`);
  }
  if (s.st === "done" && refs.length === 0) bad.push(`${id}: done without a proof reference`);
}
if (bad.length) throw new Error(`proof problems:\n${bad.join("\n")}`);
const count = (st) => [...status.values()].filter((s) => s.st === st).length;
const label = { done: "done", partial: "partial", not: "not done", server: "server only" };
const md = (s) => s.replace(/\|/g, "/");
const out = [
  "# Calendar integrations coverage (web client)",
  "",
  "Generated by `node scripts/gen-coverage-cal.mjs` from `coverage/cal-status.txt` and the calendar feature list below. The script fails when a scoped ID is missing, when a done row has no test or screenshot reference, or when a reference is unknown.",
  "",
  `Scope: the CAL- rows about subscriptions, accounts, feeds and showing external events: ${SCOPE.join(", ")}. The calendar views themselves (CAL-001..060) are M3 and stay in \`M3-COVERAGE.md\`; CAL-082..086 are parked or excluded.`,
  "",
  `Rows: ${SCOPE.length}. Done ${count("done")}, partial ${count("partial")}, not done ${count("not")}, server only ${count("server")}.`,
  "",
  "Done means a web test or a screenshot proves the behaviour in the client. Partial means built but unproven end to end, or built with a stated gap. Not done means not built or blocked on a missing server part. Server only means no web part.",
  "",
  "## How external events reach the screen",
  "",
  "`src/data/calApi.ts` keeps one shared store of subscriptions (`GET /calendar/subscription`) and accounts (`GET /calendar/third/accounts`). Each visible range fetches `GET /calendar/subscribe/events?includeHidden=true&showDeclined=true` and `GET /calendar/bind/events/all?showDeclined=true` once and caches the answer. `src/model/extCal.ts` filters and colours the events from the live source list (hidden calendars, the Show holidays and Show declined switches), so hide and recolour apply at once, and snaps all-day events to local dates (the server sends midnights in the account zone). The events join the task items in `calendarItems` as kind 3 and draw in Day, Multi-Day, Week, Multi-Week, Month, Agenda, Year (dot), the day overflow popover and both mini calendars. A click opens a popover: read-only for ICS, holidays, CalDAV and iCloud; edit and delete for two-way Google and Outlook calendars. External events cannot be dragged or resized; Arrange Tasks is untouched. Calendar calls use their own request helper because the shared client turns every 5xx into offline and drops the body (needed for 503 `oauth_not_configured` and 502 feed errors). `vite.config.ts` now proxies `/feed` so the private feed link works on the web origin.",
  "",
  "## Proof keys",
  "",
  "- `U:calext`: `test/calext.test.ts` (sources and item type numbers; colour and visibility filtering; holidays and declined switches; all-day snapping across zones; one-day, multi-day and clipped all-day layout; tasks and external events merged and sharing a day column; the two-way edit payload; feed link; subscribed list routes).",
  "- `E:zm7cal/<KEY>`: `e2e/zm7cal.spec.ts` against the real server on synthetic data with a local mock ICS feed (port 0) served by the test: CAT catalogue order and forms; OAUTH Google and Outlook not configured, Exchange unavailable; DAV refused CalDAV login; HOL server presets; SUB subscribe and week view; VIEWS month, year, agenda, mini calendar; HIDE hide and show; COLOR recolour; SIDE sidebar row and list route; FEED private feed (copy, fetch, lists, completed, reset, turn off); DISP display switches; DEL rename and unsubscribe; ACCT a two-way account with stubbed answers (page.route), since the e2e server has no Google credentials.",
  "- `S:<name>`: `screens/<name>.png` (synthetic data, desktop 1440x900 and phone 390x844, from `e2e/zm7cal-screens.spec.ts`, run with `SCREENS=1`).",
  "",
  "## Server changes wanted (not made here)",
  "",
  "- A side-effect-free status route such as `GET /api/v2/calendar/oauth/providers` (configured true/false per provider). Today the client probes `GET /oauth/{provider}/start`, which mints a 15-minute state row when credentials exist.",
  "- Exchange: no connector or routes (`/calendar/bind/exchange`, `/calendar/exchange/check`, `/calendar/bind/events/exchange/{id}`); CAL-073 stays not done.",
  "- iCloud and CalDAV are read-only on the server, so creating an event with + on iCloud (CAL-074) cannot be built.",
  "- `GET /calendar/bind/events/all` has no `includeHidden`, so hiding or showing an account calendar needs a refetch; feeds do not.",
  "- The feed config `url` is a path (`/feed/<code>.ics`); an absolute URL from the server's public origin would make the link right behind any proxy.",
  "",
  "| ID | Feature | Status | Proof / note |",
  "|---|---|---|---|",
  ...SCOPE.map((id) => `| ${id} | ${md(featureRows.get(id))} | ${label[status.get(id).st]} | ${md(status.get(id).proof)} |`),
  "",
];
writeFileSync(join(web, "CAL-COVERAGE.md"), out.join("\n"));
console.log(`CAL rows ${SCOPE.length}: done ${count("done")}, partial ${count("partial")}, not done ${count("not")}, server only ${count("server")}`);
